# The question's search as it ran before parts were searched: 8 sections, 20 candidates per
# method, every section ranking. Kept whole and first, so nothing it finds is crowded out by what
# the wider searches add.
KEPT_SECTIONS = 8
KEPT_CANDIDATES = 20
# Measured on 20 questions about the sample news, with each part keeping its own 8 sections:
# the question keeping 30 found the most and lost none of what 8 found. Ranking 30 well takes
# more candidates than the 20 each method ranks by default.
QUESTION_SECTIONS = 30
QUESTION_CANDIDATES = 50
# One part is one topic, which one search of 8 already answers well.
PART_SECTIONS = 8
PART_CANDIDATES = 20
# The events of the days a short lookup asks about given at most, in date order; the rest are
# counted. The sample news's busiest ten trading days with the trading day before (eleven
# weekdays, 2026-11-03 to 11-17) hold 25 events, so none of it is cut; it is the 30 the
# question's own search keeps.
PERIOD_EVENTS = QUESTION_SECTIONS
# A table or a note that several documents hold the same is sent once: a later copy becomes a
# pointer to the first section that sent it.
TABLE_LINE = "|"
