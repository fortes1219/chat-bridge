# The question's search as it ran before parts were searched: 8 sections, 20 candidates per
# method, every section ranking. Kept whole and first, so nothing it finds is crowded out by what
# the wider searches add.
KEPT_SECTIONS = 8
KEPT_CANDIDATES = 20
# Measured on 20 questions about the sample news, with each part keeping its own 8 sections:
# the question keeping 30 found the most and lost none of what 8 found. Ranking 30 well takes
# more candidates than the 20 each method ranks by default.
QUESTION_SECTIONS = 30
QUESTION_CANDIDATES = 50
# One part is one topic, which one search of 8 already answers well.
PART_SECTIONS = 8
PART_CANDIDATES = 20
# The section of the sample news that holds its market table (docs/truth_format.md). Its tables
# and its short preface read nearly the same in every file, so ranked on their own they match
# almost any market question whatever the event, and push the news out. So it does not rank: it
# comes with its document, as a parent document's parts come with it.
MARKET_SECTION = "當日與之後的行情"
# Sent in both languages, each on its own, so a page shows the one it is in and a reader of the
# API still gets it whatever language the question was in.
DISCLAIMER: Localized = {
    "zh-TW": "本回答由 AI 依知識庫裡的文件產生，不是投資建議。",
    "en": "This answer is generated by AI from the documents in the knowledge base and is "
    "not investment advice.",
}
# The fixed reply when the data has nothing on a question. It is an answer, so it is in the
# language of the question, as every answer is.
NOT_IN_DATA: Localized = {
    "zh-TW": "資料裡沒有相關內容。",
    "en": "The data has nothing on this.",
}
# The section names the sample news is written with (docs/truth_format.md). They are names this
# app fixed, not a document's own words, so a page shows them in its language; any other heading
# is shown as written.
SECTION_NAMES: dict[str, Localized] = {
    "事件發生": {"zh-TW": "事件發生", "en": "What happened"},
    "影響股市證據": {"zh-TW": "影響股市證據", "en": "Evidence of market impact"},
    "相關標的": {"zh-TW": "相關標的", "en": "Related assets"},
    MARKET_SECTION: {
        "zh-TW": "當日與之後的行情",
        "en": "Market moves on the day and after",
    },
    "後續與不同說法": {
        "zh-TW": "後續與不同說法",
        "en": "Later developments and other views",
    },
}
# Kept as the error of a question whose client stopped reading before the answer ended.
CUT_OFF = "the client went away before the answer ended"
# The answers still being written, each by the task writing it, so the service's shutdown can let
# them reach their records before the database stops (finish_answers).
_ANSWERING: set[asyncio.Task[Any]] = set()
PROMPT_FILE = Path(__file__).with_name("answer_prompt.md")
TEXT_DELTA = "response.output_text.delta"
PROPOSAL = "response.proposal"

# The programs that can answer, each a module with the same two functions.
PROGRAMS: dict[Program, AnsweringProgram] = {
    Program.CLAUDE_CODE: claude_code,
    Program.CODEX: codex,
}
# With no program named, the first one logged in answers. Claude Code comes first, so a user
# with both gets the same program as before Codex could answer.
PROGRAM_ORDER = (Program.CLAUDE_CODE, Program.CODEX)

# What to tell the user for each state that gives no answer, per program.
NO_LOGIN_MESSAGES: dict[Login, str] = {
    Login.NOT_INSTALLED: (
        "Claude Code is not installed. Install it and run `claude auth login`, "
        "or log in to Codex with `codex login`, then ask again."
    ),
    Login.NOT_LOGGED_IN: (
        "Claude Code is not logged in. Run `claude auth login` in a terminal, "
        "or log in to Codex with `codex login`, then ask again."
    ),
    Login.UNKNOWN: (
        "Could not tell whether Claude Code is logged in ({detail}), so no answer was "
        "given. Check `claude auth status` in a terminal."
    ),
}
CODEX_NO_LOGIN_MESSAGES: dict[Login, str] = {
    Login.NOT_INSTALLED: (
        "Codex is not installed. Install it, run `codex login`, then ask again."
    ),
    Login.NOT_LOGGED_IN: (
        "Codex is not logged in. Run `codex login` in a terminal, then ask again."
    ),
    Login.UNKNOWN: (
        "Could not tell whether Codex is logged in ({detail}), so no answer was "
        "given. Check `codex login status` in a terminal."
    ),
}
LOGIN_MESSAGES: dict[Program, dict[Login, str]] = {
    Program.CLAUDE_CODE: NO_LOGIN_MESSAGES,
    Program.CODEX: CODEX_NO_LOGIN_MESSAGES,
}


class NoLoginError(Exception):
    """The program that was to answer is not installed, not logged in, or its login could not
    be read."""

    def __init__(
        self, status: LoginStatus, program: Program = Program.CLAUDE_CODE
    ) -> None:
        super().__init__(
            LOGIN_MESSAGES[program][status.state].format(detail=status.detail)
        )


async def program_states() -> list[ProgramState]:
    """Each program's login state, read without starting a model."""
    return [
        ProgramState(
            program=program, state=(await PROGRAMS[program].login_status()).state
        )
        for program in PROGRAM_ORDER
    ]


async def choose_program(requested: Program | None) -> Program:
    """The program that answers. A named program is used only when it is logged in; it is
    never swapped for the other. With no name, the first in PROGRAM_ORDER that is logged in.
    Raises NoLoginError when none can answer."""
    if requested is not None:
        status = await PROGRAMS[requested].login_status()
        if status.state is not Login.LOGGED_IN:
            raise NoLoginError(status, requested)
        return requested
    first_refusal: NoLoginError | None = None
    for program in PROGRAM_ORDER:
        status = await PROGRAMS[program].login_status()
        if status.state is Login.LOGGED_IN:
            return program
        first_refusal = first_refusal or NoLoginError(status, program)
    raise first_refusal or NoLoginError(
        LoginStatus(Login.UNKNOWN, "no program"), PROGRAM_ORDER[0]
    )


@dataclass(frozen=True)
class FoundSection:
    section_id: int
    source: Source
    # What the model reads for this section: its whole text, not the snippet a list shows.
    text: str
    score: float


def _found_section(hit: SearchHit, number: int) -> FoundSection:
    return FoundSection(
        section_id=hit.section_id,
        source=Source(
            number=number,
            file=hit.source_path,
            title=hit.title,
            heading=hit.heading,
            heading_localizations=SECTION_NAMES.get(hit.heading),
            event_date=hit.event_date,
        ),
        text=hit.content,
        score=hit.score,
    )


async def find_sections(question: str) -> list[FoundSection]:
    """The sections the search finds for the question as asked, numbered from 1.

    First the question's search as it ran before parts were searched, whole; then the wider
    search, with market sections left out, adding what the first did not find.
    """
    kept = await search(question, KEPT_SECTIONS, candidates=KEPT_CANDIDATES)
    wide = await search(
        question,
        QUESTION_SECTIONS,
        candidates=QUESTION_CANDIDATES,
        left_out_heading=MARKET_SECTION,
    )
    seen: set[int] = set()
    hits = []
    for hit in [*kept.hits, *wide.hits]:
        if hit.section_id not in seen:
            seen.add(hit.section_id)
            hits.append(hit)
    return [_found_section(hit, number) for number, hit in enumerate(hits, start=1)]


async def gather_sections(
    question: str, sections: list[FoundSection], parts: list[str]
) -> tuple[list[FoundSection], list[dict[str, Any]]]:
    """The question's sections, then each part's in the order listed, then the market section of
    each document among them; and every search made.

    Each part keeps the sections its own search found, and none of the question's is dropped:
    nothing is cut to fit a total, because ranking the lists against each other and cutting would
    crowd a low-ranking part out again. A section found again keeps the number it got first.
    """
    numbers = {section.section_id: section.source.number for section in sections}
    gathered = list(sections)
    searches: list[dict[str, Any]] = [
        {"query": question, "numbers": [s.source.number for s in sections]}
    ]

    def add(hits: list[SearchHit]) -> list[int]:
        for hit in hits:
            if hit.section_id not in numbers:
                numbers[hit.section_id] = len(gathered) + 1
                gathered.append(_found_section(hit, numbers[hit.section_id]))
        return [numbers[hit.section_id] for hit in hits]

    if parts:
        results = await search_many(
            parts,
            PART_SECTIONS,
            candidates=PART_CANDIDATES,
            left_out_heading=MARKET_SECTION,
        )
        for part, result in zip(parts, results, strict=True):
            searches.append({"query": part, "numbers": add(result.hits)})
    attached = await sections_headed(
        [section.section_id for section in gathered], MARKET_SECTION
    )
    searches.append({"attached": MARKET_SECTION, "numbers": add(attached)})
    return gathered, searches


def question_language(question: str) -> Language:
    """Traditional Chinese when the question has a Han character, else English: the language of
    the reply that is written without a model."""
    has_han = any(HAN_FIRST <= character <= HAN_LAST for character in question)
    return "zh-TW" if has_han else "en"


@functools.cache
def _prompt_template() -> str:
    return PROMPT_FILE.read_text(encoding="utf-8")


def system_prompt(today: date) -> str:
    # Today's date lets the model say how old its sources are.
    return _prompt_template().replace("{{CURRENT_DATE}}", today.isoformat())


def model_input(question: str, sections: list[FoundSection], strategy: str = "") -> str:
    """The sources and the question, each between its own tags, so the two stay apart; for a
    question the program answers, the profile's own block between them."""
    blocks = [
        f"[{section.source.number}] file: {section.source.file}"
        f" | event date: {section.source.event_date or 'none'}"
        f" | heading: {section.source.heading or '-'}\n{section.text}"
        for section in sections
    ]
    sources = "\n\n".join(blocks)
    return (
        f"<sources>\n{sources}\n</sources>\n\n{strategy}"
        f"<question>\n{question}\n</question>\n"
    )


def _section_details(sections: list[FoundSection]) -> list[dict[str, Any]]:
    return [
        {
            "section_id": section.section_id,
            "number": section.source.number,
            "file": section.source.file,
            "heading": section.source.heading,
            "event_date": section.source.event_date.isoformat()
            if section.source.event_date
            else None,
            "score": section.score,
        }
        for section in sections
    ]


async def _record(
    question: str,
    answer: str,
    sections: list[FoundSection],
    *,
    sent_to_model: str | None,
    command_line: list[str] | None,
    error: str | None,
    program: Program | None = None,
    effort: Effort | None = None,
    split: SplitOutcome | None = None,
    searches: list[dict[str, Any]] | None = None,
    proposal: dict[str, Any] | None = None,
) -> None:
    details = {
        "sections": _section_details(sections),
        "sent_to_model": sent_to_model,
        # The program that answered, and how it was started, kept as evidence that the command
        # line held no text from the user or the documents and that its tools were off.
        "program": program,
        # The level every run of the question was started at; none when no program was asked.
        "effort": effort,
        "command_line": command_line,
        # The parts the program listed and how that run was started, or why it failed; and each
        # search made, with the numbers of the sections it returned.
        "split": None
        if split is None
        else {
            "parts": split.parts,
            "left_out": split.left_out,
            "error": split.error,
            "seconds": split.seconds,
            "command_line": split.command_line,
        },
        "searches": searches,
        # What came of a revision question's proposal: the checked proposal, the refusal, or
        # neither when the program proposed nothing.
        "proposal": proposal,
        "error": error,
    }
    async with open_engine() as engine:
        await create_tables(engine)
        sessions = async_sessionmaker(engine)
        async with sessions() as session, session.begin():
            session.add(ChatRecord(question=question, answer=answer, details=details))


async def answer_stream(
    question: str,
    sections: list[FoundSection],
    requested: Program | None = None,
    effort: Effort = DEFAULT_EFFORT,
) -> AsyncGenerator[ChatDelta, None]:
    """The context first, then the answer in pieces.

    The program is chosen before the context, so the context can name it; a refusal is still
    raised after the context, so the sources go out either way. Before the context, the chosen
    program lists the question's parts and each is searched, so the context carries every
    source. Every run of the program for the question starts at `effort`. Every question is
    recorded however the answer ends: answered, refused before the model, failed, or cut off
    because the client stopped reading. Raises NoLoginError or a ProgramError after the context
    when no answer can be had.
    """
    pieces: list[str] = []
    sent: str | None = None
    command: list[str] = []
    program: Program | None = None
    refusal: NoLoginError | None = None
    split: SplitOutcome | None = None
    searches: list[dict[str, Any]] | None = None
    # The profile as it is now, read for every question the program answers, so its advice is on
    # the person's current holdings; and the same profile when the question asks to revise the
    # strategy, none otherwise.
    current: strategy_store.Profile | None = None
    profile: strategy_store.Profile | None = None
    proposal: dict[str, Any] | None = None
    # A question the data has nothing on is answered without a model, so no login is read.
    if sections:
        try:
            program = await choose_program(requested)
        except NoLoginError as error:
            refusal = error

    async def record(error: str | None) -> None:
        await _record(
            question,
            "".join(pieces),
            sections,
            sent_to_model=sent,
            command_line=command or None,
            error=error,
            program=program,
            effort=None if program is None else effort,
            split=split,
            searches=searches,
            proposal=proposal,
        )

    answering = asyncio.current_task()
    if answering is not None:
        _ANSWERING.add(answering)
        answering.add_done_callback(_ANSWERING.discard)
    try:
        if sections and program is not None:
            current = await _profile_or_none()
            split = await split_question(
                PROGRAMS[program], question, holding_lines(current), effort=effort
            )
            # A failed split has no parts, so the question's own sections go on alone.
            sections, searches = await gather_sections(question, sections, split.parts)
            if split.revise:
                profile = current
        yield ChatDelta(
            type="response.context",
            context=ChatContext(
                sources=[section.source for section in sections],
                data_latest_date=await latest_event_date(),
                disclaimer=DISCLAIMER,
                program=program,
                split_failed=split is not None and split.failed,
                proposal_expected=profile is not None,
            ),
        )
        if not sections:
            reply = NOT_IN_DATA[question_language(question)]
            pieces.append(reply)
            yield ChatDelta(type=TEXT_DELTA, delta=reply)
            await record(None)
            return
        if refusal is not None or program is None:
            raise refusal or NoLoginError(LoginStatus(Login.UNKNOWN, "no program"))

        if profile is not None:
            sent = model_input(
                question, sections, revision.strategy_input(profile, STATE.book)
            )
            revised = await revision.revision_reply(
                PROGRAMS[program],
                revision.system_prompt(date.today()),
                sent,
                on_start=command.extend,
                effort=effort,
            )
            pieces.append(revised.answer)
            yield ChatDelta(type=TEXT_DELTA, delta=revised.answer)
            event = await revision.proposal_event(
                revised.proposal,
                profile,
                [section.source for section in sections],
                question=question,
                program=program,
            )
            proposal = event.model_dump(mode="json")
            yield ChatDelta(type=PROPOSAL, proposal=event)
            await record(None)
            return
        holdings = (
            "" if current is None else revision.strategy_input(current, STATE.book)
        )
        sent = model_input(question, sections, holdings)
        async for piece in PROGRAMS[program].stream_answer(
            system_prompt(date.today()), sent, on_start=command.extend, effort=effort
        ):
            pieces.append(piece)
            yield ChatDelta(type=TEXT_DELTA, delta=piece)
    except (NoLoginError, ProgramError) as error:
        await record(str(error))
        raise
    except (asyncio.CancelledError, GeneratorExit):
        # A cancelled task would cancel this write too, so it is shielded.
        with anyio.CancelScope(shield=True):
            await record(CUT_OFF)
        raise
    except Exception as error:
        # Anything else, such as a program that could not be started, still leaves the
        # question on record before it reaches the client.
        await record(f"{type(error).__name__}: {error}")
        raise
    await record(None)


async def finish_answers(timeout: float) -> None:
    """Let the answers still being written end and write their records, for at most `timeout`
    seconds.

    The service calls it on its way down, before it stops the database. When uvicorn's shutdown
    limit passes, uvicorn cancels the open requests and goes on to the application's shutdown
    without waiting for them; a cancelled answer writes its record as it ends, and that write needs
    the database.
    """
    pending = [task for task in _ANSWERING if not task.done()]
    if pending:
        await asyncio.wait(pending, timeout=timeout)


def holding_lines(profile: strategy_store.Profile | None) -> list[str]:
    """Each holding but cash as the split reads it: its symbol and its names, so a question about
    the user's own holdings that names none can be searched for each."""
    if profile is None:
        return []
    return [
        f"{holding.symbol}: {' / '.join(dict.fromkeys(holding.names.values()))}"
        for holding in profile.holdings
        if holding.symbol != CASH
    ]


async def _profile_or_none() -> strategy_store.Profile | None:
    """The profile as it is now. Without one, the question is answered from the sources alone,
    with no proposal asked for."""
    try:
        return await strategy_store.read_profile()
    except strategy_store.ProfileMissingError:
        return None


async def list_records(*, unanswered: bool, limit: int) -> list[ChatRecordPublic]:
    """The newest records first. `unanswered` keeps those the search found nothing for."""
    query = select(ChatRecord).order_by(ChatRecord.id.desc()).limit(limit)
    if unanswered:
        query = query.where(text(UNANSWERED))
    async with open_engine() as engine:
        await create_tables(engine)
        sessions = async_sessionmaker(engine)
        async with sessions() as session:
            records = (await session.scalars(query)).all()
    return [ChatRecordPublic.model_validate(record) for record in records]
